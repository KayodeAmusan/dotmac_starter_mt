"""``dotmac-deployment-foundation`` — one build-and-deploy facility for the fleet.

A product assembly declares `deploy/product.toml` and nothing else. Everything a
deployment needs is rendered or derived from it: the Compose file, the ingress
site, the collector configuration, the alert rules, and the ordered deployment
plan with its gates.

Read ADR-0070 for the boundary and `EXTRACTION.toml` for what was extracted from
which product and, as importantly, what was deliberately left behind.

## Three properties this package holds on purpose

**Zero runtime dependencies.** Not the kernel, not SQLAlchemy, not FastAPI, not
Jinja, not a YAML library. Standard library only — the same shape as
`dotmac-ui`, for the same reason: a build runner that renders a Compose file has
no database and no web framework, and must not acquire them to validate a
descriptor.

**No state.** No `ModuleManifest`, no models, no migrations, no lineage, no
tenant. A facility that decides how a deployment is built cannot be a table
inside one of the deployments it builds.

**No implicit runtime.** The plan is data and the executor talks to an injected
`Effects` provider. The composition gap this paragraph used to record — the
public CLI and Lane 3 rehearsal invoking a second transaction class directly
against a host provider, outside `Executor`'s grant and execution-plan checks —
is CLOSED. Exposure is a typed effect the executor performs from
`FoundationExecutionPlanV3` (carrying V2's exposure reconciliations), under the
caller's deployment lock; `exposure.py` keeps the seam and measurement and orders
nothing. `dotmac-deploy exposure-apply` observes and reports, and can no longer
apply: an `--execute` with no `--authorization` to offer was a mutation
authorized by whoever typed it.
The injected seam is what makes the failure-injection matrix — wrong digest,
failed backup, candidate never ready, maintenance-required release attempted
online — ordinary unit tests instead of disposable-VM exercises, and a gate
that has never been shown to fire is a gate nobody should trust.
"""

